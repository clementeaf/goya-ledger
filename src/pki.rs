/// Renew a node certificate: same identity (node_id), fresh key pair,
/// new validity period. The caller must revoke the old certificate via
/// LifecycleManager::revoke_and_publish_crl before calling this.
pub fn renew_node_cert(
    node_id: &str,
    ca: &NodeCaConfig,
    ttl_days: u32,
) -> Result<IssuedNodeCert, PkiError> {
    sign_node_cert(node_id, ca, ttl_days)
}

// ── provision_node_cert_if_absent ──────────────────────────────────────────

#[allow(dead_code)]
/// If `cert_path` and `key_path` do not both exist, generate a new node
/// certificate signed by the CA from environment variables and write them to
/// disk.
///
/// Returns `true` if a new cert was provisioned, `false` if both files were
/// already present (no action taken).
///
/// # Environment variables required
/// `TLS_CA_CERT_PATH` and `TLS_CA_KEY_PATH` must be set.
pub fn provision_node_cert_if_absent(
    node_id: &str,
    cert_path: &Path,
    key_path: &Path,
    ttl_days: u32,
) -> Result<bool, PkiError> {
    if cert_path.exists() && key_path.exists() {
        return Ok(false);
    }
    let ca = NodeCaConfig::from_env()?;
    let issued = sign_node_cert(node_id, &ca, ttl_days)?;
    issued.save(cert_path, key_path)?;
    Ok(true)
}

// ── FEA X.509 Adapter (Ley 19.799 / EA-103) ──────────────────────────────

pub struct FeaCertRequest {
    pub did: String,
    pub rut: String,
    pub given_name: String,
    pub surname: String,
    pub country: String,
    pub ttl_days: u32,
}

pub fn issue_fea_certificate(
    req: &FeaCertRequest,
    ca: &NodeCaConfig,
) -> Result<IssuedNodeCert, PkiError> {
    let subject = SubjectIdentity {
        given_name: Some(req.given_name.clone()),
        surname: Some(req.surname.clone()),
        serial_number: Some(req.rut.clone()),
        country: Some(req.country.clone()),
        organization: None,
        organization_id: None,
    };

    let key_pair = KeyPair::generate()?;
    let cn = format!("FEA:{}", req.did);
    let mut params = CertificateParams::new(vec![req.did.clone()])?;
    params
        .distinguished_name
        .push(DnType::CommonName, cn.as_str());

    if let Some(gn) = &subject.given_name {
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 42]), gn.as_str());
    }
    if let Some(sn) = &subject.surname {
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 4]), sn.as_str());
    }
    if let Some(serial) = &subject.serial_number {
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 5]), serial.as_str());
    }
    if let Some(c) = &subject.country {
        params
            .distinguished_name
            .push(DnType::CountryName, c.as_str());
    }

    params.is_ca = IsCa::NoCa;
    let now = time::OffsetDateTime::now_utc();
    params.not_before = now;
    params.not_after = now + time::Duration::days(i64::from(req.ttl_days));

    params
        .custom_extensions
        .push(certificate_policies_extension(
            crate::pki_policy::CP_OID,
            "https://goya.cl/pki/cp",
        ));
    params.custom_extensions.push(qc_statements_extension(
        crate::pki_policy::CertProfileType::NaturalPerson,
    ));

    let cert = params.signed_by(&key_pair, &ca.ca_cert, &ca.ca_key)?;
    let cert_der = cert.der().clone();
    let cert_pem = der_to_pem_cert(cert_der.as_ref());
    let key_pem = key_pair.serialize_pem();

    Ok(IssuedNodeCert {
        cert_der,
        cert_pem,
        key_pem,
    })
}

pub fn issue_fea_certificate_pqc(
    req: &FeaCertRequest,
    provider: &dyn crate::identity::signing::SigningProvider,
) -> Result<Vec<u8>, PkiError> {
    let now = time::OffsetDateTime::now_utc();
    let not_after = now + time::Duration::days(i64::from(req.ttl_days));
    let serial = did_to_cert_serial(&req.did);

    let mldsa_alg_oid: &[u8] = &[0x30, 0x05, 0x06, 0x03, 0x60, 0x86, 0x48];

    let mut subject_rdn_entries = Vec::new();
    add_rdn_entry(
        &mut subject_rdn_entries,
        &[2, 5, 4, 3],
        &format!("FEA:{}", req.did),
    );
    add_rdn_entry(&mut subject_rdn_entries, &[2, 5, 4, 42], &req.given_name);
    add_rdn_entry(&mut subject_rdn_entries, &[2, 5, 4, 4], &req.surname);
    add_rdn_entry(&mut subject_rdn_entries, &[2, 5, 4, 5], &req.rut);
    add_rdn_entry(&mut subject_rdn_entries, &[2, 5, 4, 6], &req.country);

    let mut subject = vec![0x30];
    let subject_content: Vec<u8> = subject_rdn_entries.into_iter().flatten().collect();
    der_push_length(&mut subject, subject_content.len());
    subject.extend_from_slice(&subject_content);

    let issuer_cn = "Goya Ledger CA";
    let mut issuer = vec![0x30];
    let issuer_entry = build_single_rdn(&[2, 5, 4, 3], issuer_cn);
    der_push_length(&mut issuer, issuer_entry.len());
    issuer.extend_from_slice(&issuer_entry);

    let pk = provider.public_key();
    let mut spki = Vec::new();
    spki.extend_from_slice(mldsa_alg_oid);
    let mut pk_bits = vec![0x00];
    pk_bits.extend_from_slice(&pk);
    let mut pk_tlv = vec![0x03];
    der_push_length(&mut pk_tlv, pk_bits.len());
    pk_tlv.extend_from_slice(&pk_bits);
    spki.extend_from_slice(&pk_tlv);
    let mut spki_seq = vec![0x30];
    der_push_length(&mut spki_seq, spki.len());
    spki_seq.extend_from_slice(&spki);

    let mut tbs = Vec::new();
    let version = [0xa0, 0x03, 0x02, 0x01, 0x02];
    tbs.extend_from_slice(&version);

    let mut serial_tlv = vec![0x02];
    der_push_length(&mut serial_tlv, serial.len());
    serial_tlv.extend_from_slice(&serial);
    tbs.extend_from_slice(&serial_tlv);

    tbs.extend_from_slice(mldsa_alg_oid);
    tbs.extend_from_slice(&issuer);

    let mut validity = Vec::new();
    let nb = format_utc_time(now.unix_timestamp() as u64);
    validity.extend_from_slice(&[0x17, nb.len() as u8]);
    validity.extend_from_slice(nb.as_bytes());
    let na = format_utc_time(not_after.unix_timestamp() as u64);
    validity.extend_from_slice(&[0x17, na.len() as u8]);
    validity.extend_from_slice(na.as_bytes());
    let mut validity_seq = vec![0x30];
    der_push_length(&mut validity_seq, validity.len());
    validity_seq.extend_from_slice(&validity);
    tbs.extend_from_slice(&validity_seq);

    tbs.extend_from_slice(&subject);
    tbs.extend_from_slice(&spki_seq);

    let mut tbs_seq = vec![0x30];
    der_push_length(&mut tbs_seq, tbs.len());
    tbs_seq.extend_from_slice(&tbs);

    let sig = provider
        .sign(&tbs_seq)
        .map_err(|_| PkiError::Rcgen(rcgen::Error::CouldNotParseCertificate))?;

    let mut sig_bits = vec![0x00];
    sig_bits.extend_from_slice(&sig);
    let mut sig_tlv = vec![0x03];
    der_push_length(&mut sig_tlv, sig_bits.len());
    sig_tlv.extend_from_slice(&sig_bits);

    let mut cert = vec![0x30];
    let total_len = tbs_seq.len() + mldsa_alg_oid.len() + sig_tlv.len();
    der_push_length(&mut cert, total_len);
    cert.extend_from_slice(&tbs_seq);
    cert.extend_from_slice(mldsa_alg_oid);
    cert.extend_from_slice(&sig_tlv);

    Ok(cert)
}

fn add_rdn_entry(entries: &mut Vec<Vec<u8>>, oid_parts: &[u64], value: &str) {
    let entry = build_single_rdn_from_oid_parts(oid_parts, value);
    entries.push(entry);
}

fn build_single_rdn(oid_der: &[u8], value: &str) -> Vec<u8> {
    let mut attr = vec![0x30];
    let oid_tlv = {
        let mut o = vec![0x06, oid_der.len() as u8];
        o.extend_from_slice(oid_der);
        o
    };
    let val_tlv = {
        let mut v = vec![0x0c];
        der_push_length(&mut v, value.len());
        v.extend_from_slice(value.as_bytes());
        v
    };
    let inner_len = oid_tlv.len() + val_tlv.len();
    der_push_length(&mut attr, inner_len);
    attr.extend_from_slice(&oid_tlv);
    attr.extend_from_slice(&val_tlv);

    let mut set = vec![0x31];
    der_push_length(&mut set, attr.len());
    set.extend_from_slice(&attr);
    set
}

fn build_single_rdn_from_oid_parts(parts: &[u64], value: &str) -> Vec<u8> {
    let oid_der = encode_oid_der(parts);
    let val_tlv = {
        let mut v = vec![0x0c];
        der_push_length(&mut v, value.len());
        v.extend_from_slice(value.as_bytes());
        v
    };

    let mut attr = vec![0x30];
    let inner_len = oid_der.len() + val_tlv.len();
    der_push_length(&mut attr, inner_len);
    attr.extend_from_slice(&oid_der);
    attr.extend_from_slice(&val_tlv);

    let mut set = vec![0x31];
    der_push_length(&mut set, attr.len());
    set.extend_from_slice(&attr);
    set
}

#[cfg(test)]
fn extract_cert_signature(cert_der: &[u8]) -> Vec<u8> {
    extract_crl_signature(cert_der, find_tbs_end(cert_der))
}

pub fn did_to_cert_serial(did: &str) -> Vec<u8> {
    use crate::crypto::hasher::{hash_with, HashAlgorithm};
    let hash = hash_with(HashAlgorithm::Sha256, did.as_bytes());
    hash[..16].to_vec()
}

pub struct RevokedEntry {
    pub serial: Vec<u8>,
    pub revocation_time: u64,
}

pub fn build_crl(revoked: &[RevokedEntry], _ca: &NodeCaConfig) -> Result<Vec<u8>, PkiError> {
    let now = time::OffsetDateTime::now_utc();

    let mut revoked_certs = Vec::new();
    for entry in revoked {
        let mut cert_entry = Vec::new();
        cert_entry.push(0x30);
        let mut inner = Vec::new();
        let mut serial_tlv = vec![0x02, entry.serial.len() as u8];
        serial_tlv.extend_from_slice(&entry.serial);
        inner.extend_from_slice(&serial_tlv);
        let utc_time = format_utc_time(entry.revocation_time);
        let mut time_tlv = vec![0x17, utc_time.len() as u8];
        time_tlv.extend_from_slice(utc_time.as_bytes());
        inner.extend_from_slice(&time_tlv);
        cert_entry.push(inner.len() as u8);
        cert_entry.extend_from_slice(&inner);
        revoked_certs.extend_from_slice(&cert_entry);
    }

    let mut tbs = Vec::new();
    tbs.extend_from_slice(&[0x02, 0x01, 0x01]);

    let alg_id: &[u8] = &[
        0x30, 0x0d, 0x06, 0x09, 0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x0b, 0x05, 0x00,
    ];
    tbs.extend_from_slice(alg_id);

    let issuer_cn = "Goya Ledger CA";
    let mut issuer_rdn = vec![0x30];
    let mut set = vec![0x31];
    let mut attr = vec![0x30];
    let cn_oid: &[u8] = &[0x06, 0x03, 0x55, 0x04, 0x03];
    let cn_val: &[u8] = &[0x0c, issuer_cn.len() as u8];
    let attr_inner_len = cn_oid.len() + cn_val.len() + issuer_cn.len();
    attr.push(attr_inner_len as u8);
    attr.extend_from_slice(cn_oid);
    attr.extend_from_slice(cn_val);
    attr.extend_from_slice(issuer_cn.as_bytes());
    set.push(attr.len() as u8);
    set.extend_from_slice(&attr);
    issuer_rdn.push(set.len() as u8);
    issuer_rdn.extend_from_slice(&set);
    tbs.extend_from_slice(&issuer_rdn);

    let this_update = format_utc_time(now.unix_timestamp() as u64);
    tbs.extend_from_slice(&[0x17, this_update.len() as u8]);
    tbs.extend_from_slice(this_update.as_bytes());

    if !revoked_certs.is_empty() {
        let mut seq = vec![0x30];
        der_push_length(&mut seq, revoked_certs.len());
        seq.extend_from_slice(&revoked_certs);
        tbs.extend_from_slice(&seq);
    }

    let mut tbs_seq = vec![0x30];
    der_push_length(&mut tbs_seq, tbs.len());
    tbs_seq.extend_from_slice(&tbs);

    let placeholder_sig: &[u8] = &[0x00; 64];
    let mut sig_bits = vec![0x00];
    sig_bits.extend_from_slice(placeholder_sig);
    let mut sig_tlv = vec![0x03];
    der_push_length(&mut sig_tlv, sig_bits.len());
    sig_tlv.extend_from_slice(&sig_bits);

    let mut crl = vec![0x30];
    let total_len = tbs_seq.len() + alg_id.len() + sig_tlv.len();
    der_push_length(&mut crl, total_len);
    crl.extend_from_slice(&tbs_seq);
    crl.extend_from_slice(alg_id);
    crl.extend_from_slice(&sig_tlv);

    Ok(crl)
}

