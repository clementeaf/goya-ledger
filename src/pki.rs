//! Internal PKI — node certificate provisioning.
//!
//! Provides a self-contained CA that issues short-lived TLS certificates for
//! P2P nodes, eliminating the dependency on an external CA.
//!
//! # Environment variables
//!
//! | Variable | Description |
//! |----------|-------------|
//! | `TLS_CA_CERT_PATH` | Path to the CA certificate PEM file (for distribution) |
//! | `TLS_CA_KEY_PATH`  | Path to the CA private key PEM file (for signing)      |
//!
//! # Design note
//!
//! When loading an existing CA from disk, this module reconstructs the rcgen
//! `Certificate` from the persisted key using a fixed Common Name
//! (`INTERNAL_CA_CN`). For the chain to validate, the CA cert on disk must have
//! been generated by `NodeCaConfig::generate` (which uses the same CN and key).
//!
//! # Example
//!
//! ```no_run
//! use rust_bc::pki::{NodeCaConfig, sign_node_cert};
//!
//! let ca = NodeCaConfig::from_env().unwrap();
//! let cert = sign_node_cert("node-1", &ca, 365).unwrap();
//! cert.save(
//!     std::path::Path::new("/etc/tls/node.crt"),
//!     std::path::Path::new("/etc/tls/node.key"),
//! ).unwrap();
//! ```

use rcgen::{BasicConstraints, CertificateParams, CustomExtension, DnType, IsCa, KeyPair};
use rustls::pki_types::CertificateDer;
use std::path::Path;

/// Common Name used for all internally-generated CA certificates.
pub const INTERNAL_CA_CN: &str = "Rust-BC Internal CA";

#[allow(dead_code)]
/// CA certificate validity (10 years from a fixed epoch).
const CA_NOT_BEFORE: time::OffsetDateTime = time::macros::datetime!(2024-01-01 0:00 UTC);
#[allow(dead_code)]
const CA_NOT_AFTER: time::OffsetDateTime = time::macros::datetime!(2034-01-01 0:00 UTC);

// ── Errors ─────────────────────────────────────────────────────────────────

#[derive(Debug, thiserror::Error)]
pub enum PkiError {
    #[error("rcgen error: {0}")]
    Rcgen(#[from] rcgen::Error),
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
    #[allow(dead_code)]
    #[error("TLS_CA_CERT_PATH must be set for PKI provisioning")]
    MissingCaCert,
    #[error("TLS_CA_KEY_PATH must be set for PKI provisioning")]
    MissingCaKey,
    #[error("cannot read file '{0}': {1}")]
    ReadFile(String, #[source] std::io::Error),
}

// ── IssuedNodeCert ─────────────────────────────────────────────────────────

#[allow(dead_code)]
/// A node certificate issued by the internal CA.
pub struct IssuedNodeCert {
    /// DER-encoded signed certificate (ready for use with rustls).
    pub cert_der: CertificateDer<'static>,
    /// PEM-encoded certificate (for writing to disk or embedding in configs).
    pub cert_pem: String,
    /// PEM-encoded private key.
    pub key_pem: String,
}

impl IssuedNodeCert {
    #[allow(dead_code)]
    /// Write cert and key to the given paths as PEM files.
    pub fn save(&self, cert_path: &Path, key_path: &Path) -> Result<(), PkiError> {
        std::fs::write(cert_path, self.cert_pem.as_bytes())?;
        std::fs::write(key_path, self.key_pem.as_bytes())?;
        Ok(())
    }
}

// ── NodeCaConfig ───────────────────────────────────────────────────────────

/// An internal CA that can sign P2P node certificates.
pub struct NodeCaConfig {
    #[allow(dead_code)]
    ca_cert: rcgen::Certificate,
    ca_key: KeyPair,
}

impl std::fmt::Debug for NodeCaConfig {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("NodeCaConfig")
            .field("ca_cn", &INTERNAL_CA_CN)
            .finish_non_exhaustive()
    }
}

impl NodeCaConfig {
    /// Access the CA certificate (for CRL signing, cert issuance).
    pub fn cert(&self) -> &rcgen::Certificate {
        &self.ca_cert
    }

    /// Access the CA key pair (for CRL signing, cert issuance).
    pub fn key(&self) -> &KeyPair {
        &self.ca_key
    }

    #[allow(dead_code)]
    /// Load a CA from PEM key file, reconstructing the rcgen signing cert.
    ///
    /// The `cert_path` file is validated (must be readable) but its content is
    /// used only for distribution — the signing cert is rebuilt from the key
    /// using [`INTERNAL_CA_CN`], which must match how the CA was originally
    /// generated.
    pub fn from_pem_files(cert_path: &Path, key_path: &Path) -> Result<Self, PkiError> {
        // Validate both paths are readable.
        let _cert_pem = std::fs::read_to_string(cert_path)
            .map_err(|e| PkiError::ReadFile(cert_path.display().to_string(), e))?;
        let key_pem = std::fs::read_to_string(key_path)
            .map_err(|e| PkiError::ReadFile(key_path.display().to_string(), e))?;
        let ca_key = KeyPair::from_pem(&key_pem)?;
        let ca_cert = make_ca_cert_params()?.self_signed(&ca_key)?;
        Ok(Self { ca_cert, ca_key })
    }

    /// Load from `TLS_CA_CERT_PATH` + `TLS_CA_KEY_PATH` environment variables.
    pub fn from_env() -> Result<Self, PkiError> {
        let cert_path = std::env::var("TLS_CA_CERT_PATH").map_err(|_| PkiError::MissingCaCert)?;
        let key_path = std::env::var("TLS_CA_KEY_PATH").map_err(|_| PkiError::MissingCaKey)?;
        Self::from_pem_files(Path::new(&cert_path), Path::new(&key_path))
    }

    #[allow(dead_code)]
    /// Generate a new self-signed CA in memory.
    ///
    /// Returns `(NodeCaConfig, cert_pem, key_pem)` so the caller can persist
    /// the cert and key to disk for future reloads and for distribution to
    /// peer nodes.
    pub fn generate() -> Result<(Self, String, String), PkiError> {
        let ca_key = KeyPair::generate()?;
        let ca_cert = make_ca_cert_params()?.self_signed(&ca_key)?;
        let cert_pem = ca_cert.pem();
        let key_pem = ca_key.serialize_pem();
        Ok((Self { ca_cert, ca_key }, cert_pem, key_pem))
    }
}

/// Build a DER-encoded certificatePolicies extension (OID 2.5.29.32).
///
/// Contains a single PolicyInformation with a CPS URI qualifier.
/// Structure: SEQUENCE { SEQUENCE { OID, SEQUENCE { SEQUENCE { OID, IA5String } } } }
pub fn certificate_policies_extension(policy_oid: &str, cps_uri: &str) -> CustomExtension {
    let policy_oid_parts: Vec<u64> = policy_oid
        .split('.')
        .filter_map(|s| s.parse().ok())
        .collect();
    let cps_qualifier_oid: &[u8] = &[0x06, 0x08, 0x2B, 0x06, 0x01, 0x05, 0x05, 0x07, 0x02, 0x01];

    let policy_oid_der = encode_oid_der(&policy_oid_parts);
    let uri_bytes = cps_uri.as_bytes();
    let uri_der = encode_ia5string_der(uri_bytes);

    let qualifier_info = encode_sequence(&[cps_qualifier_oid, &uri_der]);
    let qualifiers = encode_sequence(&[&qualifier_info]);
    let policy_info = encode_sequence(&[&policy_oid_der, &qualifiers]);
    let content = encode_sequence(&[&policy_info]);

    CustomExtension::from_oid_content(&[2, 5, 29, 32], content)
}

fn encode_oid_der(parts: &[u64]) -> Vec<u8> {
    if parts.len() < 2 {
        return vec![0x06, 0x00];
    }
    let mut body = vec![(parts[0] * 40 + parts[1]) as u8];
    for &p in &parts[2..] {
        if p < 128 {
            body.push(p as u8);
        } else {
            let mut bytes = Vec::new();
            let mut val = p;
            bytes.push((val & 0x7F) as u8);
            val >>= 7;
            while val > 0 {
                bytes.push((val & 0x7F) as u8 | 0x80);
                val >>= 7;
            }
            bytes.reverse();
            body.extend(bytes);
        }
    }
    let mut out = vec![0x06];
    encode_length(&mut out, body.len());
    out.extend(body);
    out
}

fn encode_ia5string_der(s: &[u8]) -> Vec<u8> {
    let mut out = vec![0x16];
    encode_length(&mut out, s.len());
    out.extend(s);
    out
}

fn encode_sequence(items: &[&[u8]]) -> Vec<u8> {
    let total: usize = items.iter().map(|i| i.len()).sum();
    let mut out = vec![0x30];
    encode_length(&mut out, total);
    for item in items {
        out.extend(*item);
    }
    out
}

fn encode_length(out: &mut Vec<u8>, len: usize) {
    if len < 128 {
        out.push(len as u8);
    } else if len < 256 {
        out.push(0x81);
        out.push(len as u8);
    } else {
        out.push(0x82);
        out.push((len >> 8) as u8);
        out.push(len as u8);
    }
}

#[allow(dead_code)]
/// Build `CertificateParams` for the internal CA (fixed CN and validity).
fn make_ca_cert_params() -> Result<CertificateParams, PkiError> {
    let mut params = CertificateParams::new(vec![])?;
    params
        .distinguished_name
        .push(DnType::CommonName, INTERNAL_CA_CN);
    params.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
    params.not_before = CA_NOT_BEFORE;
    params.not_after = CA_NOT_AFTER;
    params
        .custom_extensions
        .push(certificate_policies_extension(
            crate::pki_policy::CP_OID,
            "https://goya.cl/pki/cp",
        ));
    Ok(params)
}

// ── CA Hierarchy (Root + Intermediate) ────────────────────────────────────

/// Common Name for the intermediate CA.
pub const INTERMEDIATE_CA_CN: &str = "Goya Ledger Intermediate CA";

/// Two-tier CA: offline root + operational intermediate.
///
/// The root CA signs the intermediate. The intermediate signs node certs
/// and CRLs. Root key should be stored offline in production.
pub struct CaHierarchy {
    root: NodeCaConfig,
    root_cert_pem: String,
    intermediate: NodeCaConfig,
    intermediate_cert_pem: String,
}

impl std::fmt::Debug for CaHierarchy {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("CaHierarchy")
            .field("root_cn", &INTERNAL_CA_CN)
            .field("intermediate_cn", &INTERMEDIATE_CA_CN)
            .finish_non_exhaustive()
    }
}

impl CaHierarchy {
    /// Generate a new two-tier CA hierarchy in memory.
    pub fn generate() -> Result<Self, PkiError> {
        let root_key = KeyPair::generate()?;
        let root_cert = make_ca_cert_params()?.self_signed(&root_key)?;
        let root_cert_pem = root_cert.pem();

        let intermediate_key = KeyPair::generate()?;
        let intermediate_cert_params = make_intermediate_params()?;
        let intermediate_cert =
            intermediate_cert_params.signed_by(&intermediate_key, &root_cert, &root_key)?;
        let intermediate_cert_pem = der_to_pem_cert(intermediate_cert.der().as_ref());

        Ok(Self {
            root: NodeCaConfig {
                ca_cert: root_cert,
                ca_key: root_key,
            },
            root_cert_pem,
            intermediate: NodeCaConfig {
                ca_cert: intermediate_cert,
                ca_key: intermediate_key,
            },
            intermediate_cert_pem,
        })
    }

    /// The root CA (offline — use only for signing intermediates).
    pub fn root(&self) -> &NodeCaConfig {
        &self.root
    }

    /// The intermediate CA (operational — signs node certs, CRLs, OCSP).
    pub fn intermediate(&self) -> &NodeCaConfig {
        &self.intermediate
    }

    /// Root CA certificate PEM.
    pub fn root_cert_pem(&self) -> &str {
        &self.root_cert_pem
    }

    /// Intermediate CA certificate PEM.
    pub fn intermediate_cert_pem(&self) -> &str {
        &self.intermediate_cert_pem
    }

    /// Full chain PEM (intermediate + root) for TLS configuration.
    pub fn chain_pem(&self) -> String {
        format!("{}{}", self.intermediate_cert_pem, self.root_cert_pem)
    }

    /// Issue a node certificate signed by the intermediate CA.
    pub fn sign_node_cert(&self, node_id: &str, ttl_days: u32) -> Result<IssuedNodeCert, PkiError> {
        sign_node_cert(node_id, &self.intermediate, ttl_days)
    }
}

/// Build `CertificateParams` for the intermediate CA.
fn make_intermediate_params() -> Result<CertificateParams, PkiError> {
    let mut params = CertificateParams::new(vec![])?;
    params
        .distinguished_name
        .push(DnType::CommonName, INTERMEDIATE_CA_CN);
    params.is_ca = IsCa::Ca(BasicConstraints::Constrained(0));
    let now = time::OffsetDateTime::now_utc();
    params.not_before = now;
    params.not_after = now + time::Duration::days(365 * 5);
    params
        .custom_extensions
        .push(certificate_policies_extension(
            crate::pki_policy::CP_OID,
            "https://goya.cl/pki/cp",
        ));
    Ok(params)
}

/// EN 319 412-5 QCStatement OIDs beyond QcCompliance and QcType.
pub const QC_SSCD_OID: &str = "0.4.0.1862.1.4";
pub const QC_RETENTION_OID: &str = "0.4.0.1862.1.3";
pub const QC_LIMIT_VALUE_OID: &str = "0.4.0.1862.1.2";

/// Extended QCStatements parameters for qualified certificates.
pub struct QcStatementsParams {
    pub profile: crate::pki_policy::CertProfileType,
    /// Whether the signature is created by a QSCD (Qualified Signature Creation Device).
    pub qscd: bool,
    /// Retention period in years (QcRetentionPeriod). None = omit.
    pub retention_years: Option<u32>,
    /// Transaction limit value in cents (QcLimitValue). None = omit.
    pub limit_value_cents: Option<u64>,
}

/// Build raw DER content for QCStatements (EN 319 412-5).
/// Returns the SEQUENCE OF QCStatement bytes without the extension wrapper.
pub fn build_qc_statements_der(profile: crate::pki_policy::CertProfileType) -> Vec<u8> {
    build_qc_statements_der_ext(&QcStatementsParams {
        profile,
        qscd: false,
        retention_years: None,
        limit_value_cents: None,
    })
}

/// Build extended QCStatements with QSCD, retention, and limit value.
pub fn build_qc_statements_der_ext(params: &QcStatementsParams) -> Vec<u8> {
    let compliance_oid = parse_oid_str(crate::pki_policy::QC_COMPLIANCE_OID);
    let compliance_oid_der = encode_oid_der(&compliance_oid);
    let qc_compliance = encode_sequence(&[&compliance_oid_der]);

    let type_oid = parse_oid_str(crate::pki_policy::QC_TYPE_OID);
    let type_oid_der = encode_oid_der(&type_oid);

    let qc_type_value_oid = match params.profile {
        crate::pki_policy::CertProfileType::NaturalPerson => crate::pki_policy::QCT_ESIGN_OID,
        crate::pki_policy::CertProfileType::LegalPerson => crate::pki_policy::QCT_ESEAL_OID,
        crate::pki_policy::CertProfileType::WebAuthentication => crate::pki_policy::QCT_WEB_OID,
    };
    let qc_type_value_der = encode_oid_der(&parse_oid_str(qc_type_value_oid));
    let qc_type_info = encode_sequence(&[&qc_type_value_der]);
    let qc_type = encode_sequence(&[&type_oid_der, &qc_type_info]);

    let mut statements: Vec<Vec<u8>> = vec![qc_compliance, qc_type];

    if params.qscd {
        let sscd_oid_der = encode_oid_der(&parse_oid_str(QC_SSCD_OID));
        statements.push(encode_sequence(&[&sscd_oid_der]));
    }

    if let Some(years) = params.retention_years {
        let ret_oid_der = encode_oid_der(&parse_oid_str(QC_RETENTION_OID));
        let years_der = encode_integer(years as u64);
        statements.push(encode_sequence(&[&ret_oid_der, &years_der]));
    }

    if let Some(cents) = params.limit_value_cents {
        let limit_oid_der = encode_oid_der(&parse_oid_str(QC_LIMIT_VALUE_OID));
        let cents_der = encode_integer(cents);
        statements.push(encode_sequence(&[&limit_oid_der, &cents_der]));
    }

    let refs: Vec<&[u8]> = statements.iter().map(|s| s.as_slice()).collect();
    encode_sequence(&refs)
}

fn encode_integer(value: u64) -> Vec<u8> {
    let mut bytes = value.to_be_bytes().to_vec();
    while bytes.len() > 1 && bytes[0] == 0 && bytes[1] < 0x80 {
        bytes.remove(0);
    }
    let mut der = vec![0x02, bytes.len() as u8];
    der.extend_from_slice(&bytes);
    der
}

/// Build a DER-encoded QCStatements extension (OID 1.3.6.1.5.5.7.1.3).
///
/// EN 319 412-5: contains QcCompliance + QcType statements.
/// QCStatements ::= SEQUENCE OF QCStatement
/// QCStatement  ::= SEQUENCE { statementId OID, statementInfo ANY OPTIONAL }
pub fn qc_statements_extension(profile: crate::pki_policy::CertProfileType) -> CustomExtension {
    let content = build_qc_statements_der(profile);
    // id-pe-qcStatements 1.3.6.1.5.5.7.1.3
    CustomExtension::from_oid_content(&[1, 3, 6, 1, 5, 5, 7, 1, 3], content)
}

fn parse_oid_str(oid: &str) -> Vec<u64> {
    oid.split('.').filter_map(|s| s.parse().ok()).collect()
}

// ── sign_node_cert ─────────────────────────────────────────────────────────

#[allow(dead_code)]
/// Subject identity for qualified certificates (EN 319 412-2/3).
#[derive(Debug, Clone, Default)]
pub struct SubjectIdentity {
    /// Given name (EN 319 412-2, natural person).
    pub given_name: Option<String>,
    /// Surname (EN 319 412-2, natural person).
    pub surname: Option<String>,
    /// Serial number — national ID (RUT, Emirates ID, EU national ID).
    pub serial_number: Option<String>,
    /// Country code (ISO 3166-1 alpha-2).
    pub country: Option<String>,
    /// Organization name (EN 319 412-3, legal person).
    pub organization: Option<String>,
    /// Organization identifier (EORI, LEI, VAT — EN 319 412-3).
    pub organization_id: Option<String>,
}

/// Generate a new ECDSA P-256 key pair and issue a TLS certificate for
/// `node_id`, signed by `ca`.
///
/// The certificate carries `node_id` as both the Common Name and a DNS SAN,
/// and is valid for `ttl_days` days from the current time.
pub fn sign_node_cert(
    node_id: &str,
    ca: &NodeCaConfig,
    ttl_days: u32,
) -> Result<IssuedNodeCert, PkiError> {
    sign_node_cert_with_subject(node_id, ca, ttl_days, &SubjectIdentity::default())
}

/// Issue a certificate with full subject DN for qualified certificates.
pub fn sign_node_cert_with_subject(
    node_id: &str,
    ca: &NodeCaConfig,
    ttl_days: u32,
    subject: &SubjectIdentity,
) -> Result<IssuedNodeCert, PkiError> {
    let key_pair = KeyPair::generate()?;

    let mut params = CertificateParams::new(vec![node_id.to_string()])?;
    params.distinguished_name.push(DnType::CommonName, node_id);

    if let Some(gn) = &subject.given_name {
        // givenName OID 2.5.4.42
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 42]), gn.as_str());
    }
    if let Some(sn) = &subject.surname {
        // surname OID 2.5.4.4
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 4]), sn.as_str());
    }
    if let Some(serial) = &subject.serial_number {
        // serialNumber OID 2.5.4.5
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 5]), serial.as_str());
    }
    if let Some(c) = &subject.country {
        params
            .distinguished_name
            .push(DnType::CountryName, c.as_str());
    }
    if let Some(org) = &subject.organization {
        params
            .distinguished_name
            .push(DnType::OrganizationName, org.as_str());
    }
    if let Some(org_id) = &subject.organization_id {
        // organizationIdentifier OID 2.5.4.97 (ETSI EN 319 412-1)
        params
            .distinguished_name
            .push(DnType::CustomDnType(vec![2, 5, 4, 97]), org_id.as_str());
    }

    params.is_ca = IsCa::NoCa;
    let now = time::OffsetDateTime::now_utc();
    params.not_before = now;
    params.not_after = now + time::Duration::days(i64::from(ttl_days));
    params
        .custom_extensions
        .push(certificate_policies_extension(
            crate::pki_policy::CP_OID,
            "https://goya.cl/pki/cp",
        ));

    let cert = params.signed_by(&key_pair, &ca.ca_cert, &ca.ca_key)?;
    let cert_der = cert.der().clone();
    let cert_pem = der_to_pem_cert(cert_der.as_ref());
    let key_pem = key_pair.serialize_pem();

    Ok(IssuedNodeCert {
        cert_der,
        cert_pem,
        key_pem,
    })
}

